class Value:
    def __init__(self):
        self.value = None
    def set(self, value):
        self.value = value
    def get(self):
        return self.value


class RecordedController:
    def __init__(self):
        self.events = []
    def handle(self, event):
        self.events.append(event)
    def release(self):
        self.events.append({"type": "release"})


class RecordedSocket:
    def __init__(self):
        self.packets = []
    def send(self, packet, **kwargs):
        self.packets.append(packet)


class HostTests(unittest.TestCase):
    def fixture(self):
        app = HostApp.__new__(HostApp)
        app.ws = RecordedSocket(); app.current = None; app.events = queue.Queue()
        app.controller = RecordedController(); app.control_var = Value(); app.status_var = Value()
        app.access_key = "a" * 32; app.settings = (10, 800, 50); app.log = lambda _: None
        app.on_message(app.ws, json.dumps({"type": "session", "sessionId": "b" * 32}))
        viewer = Channel(app.access_key, "b" * 32, "viewer")
        app.controller.events.clear()
        return app, viewer

    def test_host_requires_valid_key_and_local_approval_before_input(self):
        app, viewer = self.fixture()
        app.on_message(app.ws, viewer.seal(1, b'{"type":"auth","name":"QA","control":true}'))
        session = app.current
        self.assertTrue(session.authenticated); self.assertFalse(session.approved)
        self.assertEqual(app.events.get()[0], "approve")
        app.on_message(app.ws, viewer.seal(1, b'{"type":"key","code":"KeyA","down":true}'))
        self.assertEqual(app.controller.events, [])
        self.assertEqual(app.ws.packets, [])
        # Simulate the approved state; no native Windows input is generated by this test.
        session.approved = True; session.control = False
        app.on_message(app.ws, viewer.seal(1, b'{"type":"key","code":"KeyA","down":true}'))
        self.assertEqual(app.controller.events, [])
        session.control = True
        app.on_message(app.ws, viewer.seal(1, b'{"type":"key","code":"KeyA","down":true}'))
        self.assertEqual(app.controller.events[0]["code"], "KeyA")
        app.end_current()
        self.assertIsNone(app.current); self.assertTrue(session.stopped.is_set())
        self.assertEqual(app.controller.events[-1]["type"], "release")

    def test_wrong_key_does_not_open_an_approval_prompt(self):
        app, _ = self.fixture()
        wrong = Channel("c" * 32, "b" * 32, "viewer")
        app.on_message(app.ws, wrong.seal(1, b'{"type":"auth","name":"QA","control":true}'))
        self.assertIsNone(app.current)
        events = []
        while not app.events.empty():
            events.append(app.events.get()[0])
        self.assertNotIn("approve", events)

    def test_stream_sends_real_jpeg_only_after_approval_and_waits_for_ack(self):
        app, viewer = self.fixture(); session = app.current
        app.on_message(app.ws, viewer.seal(1, b'{"type":"auth","name":"QA","control":false}'))
        with patch("app.DesktopCapture") as capture:
            capture.return_value.grab.side_effect = lambda **_: Image.new("RGB", (640, 360), "green")
            app.begin_approved_session(session, "QA", False)
            deadline = time.monotonic() + 3
            while len(app.ws.packets) < 3 and time.monotonic() < deadline:
                time.sleep(.02)
            self.assertGreaterEqual(len(app.ws.packets), 3)
            encrypted = [packet for packet in app.ws.packets if isinstance(packet, bytes)]
            approved = viewer.open(encrypted[0]); frame = viewer.open(encrypted[1])
            self.assertEqual(json.loads(approved[1])["type"], "approved")
            self.assertEqual(frame[0], 2); self.assertTrue(frame[1].startswith(b"\xff\xd8"))
            count = len(app.ws.packets)
            time.sleep(.25)
            self.assertEqual(len(app.ws.packets), count, "Frames must wait for the viewer acknowledgement")
            app.end_current()

    def test_high_fps_sends_bounded_pipeline_and_ack_unblocks_one_slot(self):
        app, viewer = self.fixture(); session = app.current
        app.settings = (60, 800, 50)
        app.on_message(app.ws, viewer.seal(1, b'{"type":"auth","name":"QA","control":false}'))
        with patch("app.DesktopCapture") as capture:
            capture.return_value.grab.side_effect = lambda **_: Image.new("RGB", (640, 360), "green")
            app.begin_approved_session(session, "QA", False)
            deadline = time.monotonic() + 3
            while len(session.frames.pending) < 8 and time.monotonic() < deadline:
                time.sleep(.01)
            self.assertEqual(len(session.frames.pending), 8)
            count = len(app.ws.packets)
            time.sleep(.15)
            self.assertEqual(len(app.ws.packets), count, "The pipeline must stop when its window is full")
            app.on_message(app.ws, viewer.seal(1, b'{"type":"ack"}'))
            deadline = time.monotonic() + 2
            while len(app.ws.packets) == count and time.monotonic() < deadline:
                time.sleep(.01)
            self.assertEqual(len(app.ws.packets), count + 1)
            self.assertEqual(len(session.frames.pending), 8)
            app.end_current()

    def test_crypto_replay_wrong_key_and_tamper(self):
        secret, sid = "a" * 32, "b" * 32
        host, viewer = Channel(secret, sid), Channel(secret, sid, "viewer")
        packet = host.seal(1, b'{"test":1}')
        wrong = Channel("c" * 32, sid, "viewer")
        with self.assertRaises(Exception):
            wrong.open(packet)
        damaged = bytearray(packet); damaged[-1] ^= 1
        with self.assertRaises(Exception):
            viewer.open(bytes(damaged))
        self.assertEqual(viewer.open(packet), (1, b'{"test":1}'))
        with self.assertRaises(ValueError):
            viewer.open(packet)

    def test_urls_require_tls_outside_loopback(self):
        self.assertEqual(server_url("http://localhost:8787"), "ws://localhost:8787/ws")
        self.assertEqual(server_url("https://desk.example.edu/"), "wss://desk.example.edu/ws")
        for url in ("http://192.0.2.10:8787", "http://example.edu", "https://user:pass@example.edu", "https://example.edu/path", "file:///test", "https://example.edu?a=b"):
            with self.assertRaises(ValueError):
                server_url(url)

    def test_native_input_size_and_reject_invalid_events_without_injection(self):
        self.assertEqual(ctypes.sizeof(INPUT), 40 if ctypes.sizeof(ctypes.c_void_p) == 8 else 28)
        controller = Controller()
        for msg in ({"type": "move", "x": float("nan"), "y": 0}, {"type": "move", "x": -1, "y": 0}, {"type": "wheel", "delta": "bad"}, {"type": "key", "code": "KeyA", "down": "true"}):
            with self.assertRaises(ValueError):
                controller.handle(msg)
        self.assertEqual(controller.keys, set())
        self.assertEqual(KEYS["KeyA"], 65)


